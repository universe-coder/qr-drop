/**
 * CRC-32C (Castagnoli): полином 0x1EDC6F41, отражённая форма 0x82F63B78,
 * init 0xFFFFFFFF, refin/refout, xorout 0xFFFFFFFF.
 *
 * Почему 32 бита, а не 16: фонтанный декодер подмешивает содержимое кадра
 * сразу в несколько исходных блоков, поэтому один незамеченный повреждённый
 * кадр тихо портит весь файл, а обнаруживается это только финальным SHA-256 —
 * то есть после нескольких минут съёмки. 2^-32 против 2^-16 стоит двух байт.
 *
 * Почему Castagnoli, а не IEEE: на длинах наших кадров (до ~1 КБ) он держит
 * гарантированное расстояние Хэмминга 6, тогда как обычный CRC-32 опускается
 * до 4 уже после ~375 байт.
 *
 * Настоящая работа этого CRC — ловить не порчу бит (её почти целиком снимает
 * собственная коррекция QR), а ошибки кадрирования: недосканированный код,
 * два кода, попавших в один снимок, устаревший буфер.
 */

const TABLE = /* @__PURE__ */ (() => {
  const table = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) {
      c = c & 1 ? 0x82f63b78 ^ (c >>> 1) : c >>> 1;
    }
    table[n] = c >>> 0;
  }
  return table;
})();

export function crc32c(bytes: Uint8Array, start = 0, end = bytes.length): number {
  let crc = 0xffffffff;
  for (let i = start; i < end; i++) {
    crc = TABLE[(crc ^ bytes[i]) & 0xff] ^ (crc >>> 8);
  }
  return (crc ^ 0xffffffff) >>> 0;
}
